/**
 * 方块 id 的**分配表**（批次 20261025-1032）
 *
 * 这个文件是**叶子模块**：不 import 任何东西，只放纯字面量。它存在的原因只有一个——
 * 方块表数据（`blockSpecs.ts`）要读这些 id，而数据一旦反向 import `blocks.ts`，
 * 就成了"数据 ← 核心 ← 数据"的环：ESM 原生能靠"已初始化的绑定"绕过去，但打包器把
 * 模块初始化拍平成同步函数后就是**互等死锁**（上一批实测：`Detected unsettled top-level await`）。
 *
 * 所以依赖方向固定为：
 *
 *     blockIds.ts（本文件，叶子） → blockSpecs.ts（数据） → blocks.ts（消费 + 再导出）
 *
 * `blocks.ts` 用 `export *` 把这里的名字原样透出去，**224 个引用方一行都不用改**。
 *
 * ⚠️ 这里只能放"值不依赖任何模块"的东西（字面量、字面量之间的算术）。
 * 凡是需要 `DYE_COLORS` / `WOOD_TYPES` / 方块表才能算出来的 id（`Wood` / `BED_IDS` /
 * `SAPLING_IDS` …）都留在 `blocks.ts`，否则叶子就不"叶子"了。
 */

