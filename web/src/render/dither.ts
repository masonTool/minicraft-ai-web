/**
 * 屏幕空间的**抖色**（批次 520）
 *
 * ## 为什么要它
 *
 * 帧缓冲是 8 bit/通道，而天空穹顶、雾、渐变的暗部都是**大面积的平滑渐变**：
 * 相邻两级亮度差不到 1/255 时，GPU 只能把它们取整到同一级 —— 于是渐变里出现
 * 一圈圈横向色带。白天不明显，**夜里、洞里、下界的暗部最明显**（用户说的
 * "画面不平滑"很大一部分就是它，而不是分辨率或抗锯齿）。
 *
 * ## 做法
 *
 * 在最终颜色上加 ±0.5/255 的 **4×4 Bayer 有序抖动**：把"取整到哪一级"的边界
 * 打散成棋盘状的点，肉眼看不到噪点，但色带的台阶消失了。幅度取 1/255 是刻意的
 * ——正好一个量化级，再大就会变成"颗粒"（与我们在植物上要消除的东西相反）。
 *
 * 用有序抖动而不是随机噪声：随机会在**静止画面**上留下闪烁的噪点（每帧不一样），
 * 有序图案是固定的，画面完全静止。
 *
 * 两个着色器（体素材质、天空穹顶）都从这里取同一段 GLSL，避免各写一版。
 */

/** 抖色强度的倒数：255 = 恰好一个 8 bit 量化级 */
const DITHER_LEVELS = 255;

/**
 * 注入到片元着色器里的三个函数。
 *
 * ⚠️ GLSL ES 1.0 **不允许嵌套函数定义**，所以 `bayer2` / `bayer4` 必须是平级的
 * 顶层函数，不能用闭包写法。
 */
export const GLSL_DITHER = /* glsl */ `
/** 2×2 Bayer：把坐标按 2 取整后算一个 0~1 的图案 */
float bayer2(vec2 a) {
  a = floor(a);
  return fract(a.x * 0.5 + a.y * a.y * 0.75);
}
/** 4×4 Bayer：两层 2×2 叠起来（经典写法，返回 0~1） */
float bayer4(vec2 a) {
  return bayer2(0.5 * a) * 0.25 + bayer2(a);
}
/** 最终颜色 + 一个量化级以内的有序抖动 */
vec3 ditherColor(vec3 color, vec2 fragCoord) {
  return color + (bayer4(fragCoord) - 0.5) / ${DITHER_LEVELS}.0;
}
`;
